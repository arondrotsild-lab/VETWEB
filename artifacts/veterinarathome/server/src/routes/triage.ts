function rulesTriage(text: string): Triage {
  const r = RULES.find((rule) => rule.re.test(text));
  if (r) return { urgency: r.urgency, summary: r.summary, do_now: r.do_now, dont: r.dont, possible_causes: r.causes, recommended_service: r.service, source: 'rules' };
  return {
    urgency: 'routine', source: 'rules',
    summary: 'Срочных признаков по описанию не видно — врач осмотрит питомца и всё проверит.',
    do_now: ['Обеспечьте питомцу покой и доступ к воде', 'Подготовьте ветеринарный паспорт и список лекарств, которые он получает', 'Если состояние ухудшится — выберите «Скорая ветпомощь»'],
    dont: ['Не давайте человеческие лекарства без консультации врача'],
    possible_causes: 'Точную причину определит врач на осмотре.', recommended_service: 'Первичный осмотр',
  };
}

const router = Router();
router.use(authMiddleware);

// POST /api/triage — { text, pet } → предварительная оценка
router.post('/', async (req: AuthRequest, res: Response) => {
  const text = String(req.body?.text || '').trim().slice(0, 4000);
  const pet = String(req.body?.pet || '').slice(0, 200);
  if (text.length < 5) {
    res.status(400).json({ error: 'Опишите, что происходит с питомцем' });
    return;
  }
  const result = (await aiTriage(text, pet)) ?? rulesTriage(text);
  res.json(result);
});

export default router;
